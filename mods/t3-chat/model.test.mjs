// T3's timeline: work folded into groups between the messages; a meta row after a finished turn.
const stamp = (entry, seconds) => ({ ...entry, timestamp: new Date(Date.parse(at) + seconds * 1000).toISOString() });
const turn = applyTranscript(emptyChat(), [
  stamp(user("fix it"), 0),
  stamp(assistant([{ type: "thinking", thinking: "plan" }]), 2),
  stamp(assistant([{ type: "tool_use", id: "w1", name: "Bash", input: { command: "ls" } }]), 5),
  stamp(user([{ type: "tool_result", tool_use_id: "w1", content: "a" }]), 51),
  stamp(assistant([{ type: "tool_use", id: "w2", name: "TodoWrite", input: { todos: [{ content: "x", status: "pending" }] } }]), 52),
  stamp(assistant([{ type: "text", text: "Looking." }]), 53),
  stamp(assistant([{ type: "tool_use", id: "w3", name: "Edit", input: { file_path: "/src/a.js", old_string: "a", new_string: "b" } }]), 60),
]);
const live = timeline(turn, { isWorking: true });
assert.deepEqual(live.map((r) => r.kind), ["user", "work", "text", "work"]);
assert.deepEqual(live[1].entries.map((e) => e.kind), ["thinking", "tool"]); // the todo list is not work
assert.deepEqual([live[1].endedAt - live[1].startedAt, live[1].isLive, live[3].isLive], [49, false, true]);
assert.equal(live[3].startedAt - live[3].turnStartedAt, 60); // a live group counts from the turn's start
const done = timeline(applyTranscript(turn, [stamp(user([{ type: "tool_result", tool_use_id: "w3", content: "ok" }]), 70), stamp(assistant([{ type: "text", text: "Done." }]), 75)]));
assert.deepEqual(done.map((r) => r.kind), ["user", "work", "text", "work", "text", "changed", "meta"]);
assert.deepEqual([done[6].text, done[6].endedAt - done[6].startedAt], ["Looking.\n\nDone.", 75]);
